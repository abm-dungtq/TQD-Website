# CLI
# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB, help="path to the D1 SQL dump")
    parser.add_argument(
        "--env",
        default=None,
        metavar="NAME",
        help="environment name in environment.json (default: the `default` entry, else local)",
    )
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument(
        "--env",
        default=argparse.SUPPRESS,
        metavar="NAME",
        help="environment name in environment.json (default: the `default` entry, else local)",
    )
    sub = parser.add_subparsers(dest="command")
    sub.add_parser("generate", help="write posts/ and media-map.json from the D1 dump")
    media_parser = sub.add_parser("media", help="download D1 media into api/v1/media")
    media_parser.add_argument("--workers", type=int, default=6)
    upload_parser = sub.add_parser(
        "upload-media",
        parents=[common],
        help="upload api/v1/media files to the selected EzyPlatform media library",
    )
    upload_parser.add_argument("--apply", action="store_true", help="upload (default: dry run)")
    publish_parser = sub.add_parser(
        "publish",
        parents=[common],
        help="create/update posts and sync tags on the selected EzyPlatform",
    )
    publish_parser.add_argument("--apply", action="store_true", help="write to the server (default: dry run)")
    tags_parser = sub.add_parser(
        "tags",
        parents=[common],
        help="sync tqd_tags post meta for migrated articles",
    )
    tags_parser.add_argument("--apply", action="store_true", help="write to the server (default: dry run)")
    sub.add_parser("verify", parents=[common], help="read-only checks against the selected EzyPlatform")
    args = parser.parse_args(argv)
    command = args.command or "generate"
    env_name = getattr(args, "env", None)

    try:
        if command == "publish":
            result = publish(apply=args.apply, env_name=env_name)
            print(json.dumps(result, ensure_ascii=False, indent=2))
        elif command == "tags":
            result = sync_tags(apply=args.apply, env_name=env_name)
            print(json.dumps(result, ensure_ascii=False, indent=2))
        elif command == "verify":
            report = verify(env_name=env_name)
            print(json.dumps(report, ensure_ascii=False, indent=2))
            broken = [key for key, value in report.items() if isinstance(value, list) and value]
            if broken:
                print("verify failed: " + ", ".join(broken), file=sys.stderr)
                return 3
        elif command == "upload-media":
            conn = load_db(args.db)
            try:
                result = upload_media(conn, args.apply, env_name=env_name)
            finally:
                conn.close()
            print(json.dumps(result, ensure_ascii=False, indent=2))
        else:
            conn = load_db(args.db)
            try:
                if command == "media":
                    result = download_media(conn, args.workers)
                else:
                    result = generate(conn)
            finally:
                conn.close()
            print(json.dumps(result, ensure_ascii=False, indent=2))
    except MigrationError as err:
        print(f"error: {err}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
