def download_media_file(key: str, name: str, expected_size: int, content_type: str) -> tuple[str, str]:
    target = MEDIA_DIR / name
    if target.is_file() and target.stat().st_size == expected_size:
        return "skipped", name

    url = MEDIA_BASE + urllib.parse.quote(key, safe="/")
    last_error: Exception | None = None
    for attempt in range(1, 4):
        try:
            request = urllib.request.Request(
                url, headers={"User-Agent": "tqd-migrate/1.0 (+https://tqd.me)"}
            )
            with urllib.request.urlopen(request, timeout=90) as response:
                data = response.read()
            if len(data) != expected_size:
                raise MigrationError(
                    f"{key}: downloaded {len(data)} bytes, D1 media table says {expected_size}"
                )
            served_type = response.headers.get("Content-Type", "").split(";")[0].strip().lower()
            if served_type and served_type != "application/octet-stream" and served_type != content_type.lower():
                print(f"  ! {key}: served as {served_type}, D1 says {content_type}", file=sys.stderr)
            MEDIA_DIR.mkdir(parents=True, exist_ok=True)
            temporary = target.with_name(target.name + ".part")
            temporary.write_bytes(data)
            os.replace(temporary, target)
            return "downloaded", name
        except (urllib.error.URLError, TimeoutError, OSError, MigrationError) as err:
            last_error = err
            if attempt < 3:
                time.sleep(attempt)
    raise MigrationError(f"{key}: {last_error}")


def download_media(conn: sqlite3.Connection, workers: int) -> dict[str, Any]:
    rows = [dict(row) for row in conn.execute("SELECT * FROM media ORDER BY key")]
    if len(rows) != EXPECTED_MEDIA:
        raise MigrationError(f"expected {EXPECTED_MEDIA} media rows, found {len(rows)}")
    mapping = parse_media_keys(conn)
    results: dict[str, int] = {"downloaded": 0, "skipped": 0, "failed": 0}
    failures: list[str] = []
    total = 0
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {
            pool.submit(download_media_file, row["key"], mapping[row["key"]], int(row["size"]), row["content_type"]): row
            for row in rows
        }
        for future in as_completed(futures):
            row = futures[future]
            try:
                action, name = future.result()
                results[action] += 1
                total += int(row["size"])
                if action == "downloaded":
                    print(f"  + {name} ({row['size']} bytes)")
            except MigrationError as err:
                results["failed"] += 1
                failures.append(str(err))
                print(f"  x {err}", file=sys.stderr)

    missing = []
    for row in rows:
        name = mapping[row["key"]]
        path = MEDIA_DIR / name
        if not path.is_file() or path.stat().st_size != int(row["size"]):
            missing.append(name)

    report = {
        "expected": len(rows),
        "byAction": results,
        "bytesExpected": sum(int(row["size"]) for row in rows),
        "bytesDownloaded": total,
        "missingOnDisk": missing,
        "failures": failures,
    }
    write_json(MIGRATE_DIR / "media-report.json", report)
    if failures or missing:
        raise MigrationError(
            f"{results['failed']} download(s) failed, {len(missing)} file(s) missing or wrong size on disk"
        )
    return report


