def upload_media(conn: sqlite3.Connection, apply: bool, env_name: str | None = None) -> dict[str, Any]:
    rows = [dict(row) for row in conn.execute("SELECT * FROM media ORDER BY key")]
    if len(rows) != EXPECTED_MEDIA:
        raise MigrationError(f"expected {EXPECTED_MEDIA} media rows, found {len(rows)}")
    mapping = parse_media_keys(conn)
    client = EzyClient(env_name)

    pending: list[tuple[dict[str, Any], str, Path]] = []
    already: list[str] = []
    for row in rows:
        name = mapping[row["key"]]
        path = MEDIA_DIR / name
        if not path.is_file():
            raise MigrationError(f"{name}: local file is missing (run the media command first)")
        if path.stat().st_size != int(row["size"]):
            raise MigrationError(f"{name}: local size does not match the D1 media table")
        if client.media_contains(name):
            already.append(name)
        else:
            pending.append((row, name, path))

    actions = [
        {"file": name, "bytes": int(row["size"]), "mimeType": row["content_type"]}
        for row, name, _ in pending
    ]
    report: dict[str, Any] = {
        "applied": apply,
        "total": len(rows),
        "alreadyOnServer": len(already),
        "toUpload": len(pending),
        "uploaded": 0,
        "actions": actions,
    }
    if not apply:
        write_json(MIGRATE_DIR / "media-upload-plan.json", report)
        return report

    for row, name, path in pending:
        client.upload_media(name, path.read_bytes(), row["content_type"])
        report["uploaded"] += 1
        print(f"  ✓ {name} ({row['size']} bytes, {row['content_type']})")

    missing = [name for name in mapping.values() if not client.media_contains(name)]
    report["missingAfterUpload"] = missing
    write_json(MIGRATE_DIR / "media-upload-report.json", report)
    if missing:
        raise MigrationError(f"{len(missing)} media file(s) still missing on the server")
    return report


