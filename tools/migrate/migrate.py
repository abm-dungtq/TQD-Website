def load_db(path: Path) -> sqlite3.Connection:
    if not path.is_file():
        raise MigrationError(f"D1 dump not found: {path}")
    conn = sqlite3.connect(":memory:")
    conn.row_factory = sqlite3.Row
    try:
        conn.executescript(path.read_text(encoding="utf-8"))
    except sqlite3.Error as err:
        raise MigrationError(f"cannot load {path}: {err}") from err
    return conn


def slugify(value: str, max_len: int = 80) -> str:
    """ASCII slug: Vietnamese diacritics removed, punctuation collapsed to '-'."""
    value = unicodedata.normalize("NFD", value)
    value = "".join(ch for ch in value if unicodedata.category(ch) != "Mn")
    value = value.replace("đ", "d").replace("Đ", "D").lower()
    value = re.sub(r"[^a-z0-9]+", "-", value).strip("-")
    if len(value) > max_len:
        value = value[:max_len].rsplit("-", 1)[0].rstrip("-")
    if not value:
        raise MigrationError("cannot derive a slug from an empty value")
    return value


def flatten_key(key: str) -> str:
    name = key.replace("/", "-")
    if not MEDIA_NAME_RE.match(name):
        raise MigrationError(f"media key {key!r} becomes an invalid media name {name!r}")
    return name


def parse_media_keys(conn: sqlite3.Connection) -> dict[str, str]:
    keys = [row["key"] for row in conn.execute("SELECT key FROM media ORDER BY key")]
    mapping = {key: flatten_key(key) for key in keys}
    if len(mapping) != EXPECTED_MEDIA:
        raise MigrationError(f"expected {EXPECTED_MEDIA} media rows, found {len(mapping)}")
    if len(set(mapping.values())) != len(mapping):
        raise MigrationError("two media keys flatten to the same file name")
    return mapping


def rewrite_media_urls(markup: str, name_by_key: dict[str, str], where: str) -> str:
    unresolved: list[str] = []

    def replace(match: re.Match[str]) -> str:
        raw = match.group(1)
        key = urllib.parse.unquote(raw.split("?", 1)[0].split("#", 1)[0])
        name = name_by_key.get(key)
        if not name:
            unresolved.append(key)
            return match.group(0)
        return "/api/v1/media/" + name

    out = TQDM_MEDIA_RE.sub(replace, markup)
    if unresolved:
        sample = ", ".join(sorted(set(unresolved))[:5])
        raise MigrationError(f"{where}: media URL(s) not present in the media table: {sample}")
    return out


def html_text(fragment: str) -> str:
    return html.unescape(TAG_RE.sub("", fragment)).strip()


def strip_runtime_markup(markup: str) -> tuple[str, int]:
    """Remove Astro hydration scripts and build-specific attributes from a card."""
    without_scripts, scripts = SCRIPT_RE.subn("", markup)
    without_attrs, attrs = ASTRO_ATTR_RE.subn("", without_scripts)
    return without_attrs.strip(), scripts + attrs


def published_at_from_item_date(value: str | None) -> str | None:
    if not value:
        return None
    match = DATE_DMY_RE.match(value.strip())
    if not match:
        return None
    day, month, year = match.groups()
    return f"{year}-{month}-{day} 00:00:00"


def write_if_changed(path: Path, data: str) -> bool:
    encoded = data.encode("utf-8")
    if path.is_file() and path.read_bytes() == encoded:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data, encoding="utf-8", newline="")
    return True


def write_json(path: Path, value: Any) -> bool:
    return write_if_changed(path, json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def parse_article_tags(value: str | None) -> list[str]:
    """Parse the D1 `articles.tags` JSON array, preserving its order."""
    if not value:
        return []
    try:
        tags = json.loads(value)
    except json.JSONDecodeError as err:
        raise MigrationError(f"articles.tags is not valid JSON: {value!r}") from err
    if not isinstance(tags, list) or not all(isinstance(tag, str) for tag in tags):
        raise MigrationError(f"articles.tags must be a JSON array of strings: {value!r}")
    return tags


def compact_tags(tags: list[str]) -> str:
    """Serialize tags the same compact way the D1 dump stores them."""
    return json.dumps(tags, ensure_ascii=False, separators=(",", ":"))


