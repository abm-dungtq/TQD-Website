VN_TZ = dt.timezone(dt.timedelta(hours=7))

EXPECTED_ARTICLES = 22
EXPECTED_ITEMS = 21
EXPECTED_GALLERY = 4
EXPECTED_MEDIA = 119
MEDIA_NAME_RE = re.compile(r"^[a-zA-Z0-9_-]+(\.[a-zA-Z0-9_-]+)*$")
TQDM_MEDIA_RE = re.compile(r"(?:(?:https?:)?//tqd\.me)?/media/([^\s\"'<>()]+)")
SCRIPT_RE = re.compile(r"<script\b[^>]*>.*?</script>", re.S | re.I)
ASTRO_ATTR_RE = re.compile(r"\s+data-astro-[a-zA-Z0-9_-]+=\"[^\"]*\"")
ARTICLE_RE = re.compile(r'<article class="lux-card[^"]*"[^>]*>.*?</article>', re.S)
FIGURE_RE = re.compile(r'<figure class="lux-card gallery-item"[^>]*>.*?</figure>', re.S)
H2_RE = re.compile(r"<h[23]\b[^>]*>(.*?)</h[23]>", re.S)
FIGCAPTION_RE = re.compile(r"<figcaption\b[^>]*>(.*?)</figcaption>", re.S)
TAG_RE = re.compile(r"<[^>]+>")
DATE_DMY_RE = re.compile(r"^(\d{2})/(\d{2})/(\d{4})$")
DATETIME_RE = re.compile(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$")

POST_TYPES = {"POST", "tqd_product", "tqd_video", "tqd_gallery"}
