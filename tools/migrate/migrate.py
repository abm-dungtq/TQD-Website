MIGRATE_DIR = ROOT / ".artifacts" / "migrate"
LIVE_DIR = ROOT / ".artifacts" / "live"
MEDIA_MAP_PATH = ROOT / "tools" / "migrate" / "media-map.json"
MANIFEST_PATH = MIGRATE_DIR / "manifest.json"
REPORT_PATH = MIGRATE_DIR / "report.json"
MEDIA_BASE = "https://tqd.me/media/"
TAGS_META_KEY = "tqd_tags"
