def load_snapshot_cards(filename: str, pattern: re.Pattern[str], title_pattern: re.Pattern[str]) -> dict[str, str]:
    path = LIVE_DIR / filename
    if not path.is_file():
        raise MigrationError(f"snapshot missing: {path}")
    text = path.read_text(encoding="utf-8")
    cards: dict[str, str] = {}
    for match in pattern.finditer(text):
        card = match.group(0)
        title_match = title_pattern.search(card)
        if not title_match:
            continue
        title = html_text(title_match.group(1))
        if title in cards:
            raise MigrationError(f"{filename}: duplicate card title {title!r}")
        cards[title] = card
    return cards


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def build_item_card(item: sqlite3.Row, name_by_key: dict[str, str]) -> str:
    """Recreate ItemCard.astro for an item the live snapshot does not contain."""
    title = item["title"]
    cover = item["cover_key"]
    parts = ['<article class="lux-card flex flex-col gap-3 p-6">']
    if cover and cover in name_by_key:
        parts.append(
            f'<img src="/api/v1/media/{name_by_key[cover]}" alt="{esc(title)}" '
            'width="640" height="360" loading="lazy" decoding="async" '
            'class="aspect-video w-full rounded-xl border border-line object-cover">'
        )
    parts.append("<div>")
    if item["date"]:
        parts.append(f'<p class="font-mono text-xs text-muted">{esc(item["date"])}</p>')
    parts.append(f'<h2 class="display mt-1 text-2xl">{esc(title)}</h2>')
    parts.append("</div>")
    parts.append(f'<p class="text-sm leading-relaxed">{esc(item["summary"])}</p>')

    tags = json.loads(item["tags"] or "[]")
    if tags:
        parts.append('<ul class="mt-auto flex flex-wrap gap-1.5" aria-label="Nhãn">')
        for tag in tags:
            parts.append(f'<li class="lux-chip px-2.5 py-0.5 text-xs">{esc(str(tag))}</li>')
        parts.append("</ul>")

    links = json.loads(item["links"] or "[]")
    if links:
        parts.append('<p class="flex flex-wrap gap-3 text-sm font-semibold">')
        for link in links:
            href = str(link.get("href", ""))
            label = esc(str(link.get("label", "")))
            external = not href.startswith("/")
            attrs = ' target="_blank" rel="noopener noreferrer"' if external else ""
            parts.append(
                f'<a href="{esc(href)}" class="inline-flex min-h-11 -my-2 items-center"{attrs}>{label} →</a>'
            )
        parts.append("</p>")
    parts.append("</article>")
    return "".join(parts)


def build_gallery_card(entry: dict[str, Any], name_by_key: dict[str, str]) -> str:
    """Recreate the thu-vien <figure> for a gallery entry the snapshot lacks."""
    caption = str(entry["caption"])
    key = str(entry["key"])
    name = name_by_key[key]
    parts = ['<figure class="lux-card gallery-item">']
    if key.lower().endswith(".mp4"):
        poster = entry.get("poster")
        poster_attr = ""
        if poster and poster in name_by_key:
            poster_attr = f' poster="/api/v1/media/{name_by_key[poster]}"'
        parts.append(
            f'<video src="/api/v1/media/{name}"{poster_attr} controls playsinline '
            f'preload="none" width="1280" height="720" aria-label="{esc(caption)}"></video>'
        )
    else:
        parts.append(
            f'<a href="/api/v1/media/{name}" target="_blank" rel="noopener noreferrer" '
            f'aria-label="Xem ảnh lớn: {esc(caption)}">'
            f'<img src="/api/v1/media/{name}" alt="{esc(caption)}" width="1280" height="720" '
            'loading="lazy" decoding="async"></a>'
        )
    parts.append(f'<figcaption class="p-4 text-sm leading-relaxed">{esc(caption)}</figcaption>')
    parts.append("</figure>")
    return "".join(parts)


