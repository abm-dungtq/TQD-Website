def load_environment(name: str | None = None) -> tuple[str, str, str]:
    """Return (name, admin_url, token) from environment.json without printing the token."""
    if not ENVIRONMENT_PATH.is_file():
        raise MigrationError("environment.json not found")
    try:
        environments = json.loads(ENVIRONMENT_PATH.read_text(encoding="utf-8"))
    except json.JSONDecodeError as err:
        raise MigrationError(f"environment.json is invalid: {err}") from err
    if not isinstance(environments, list) or not environments:
        raise MigrationError("environment.json must contain a non-empty array")

    if name:
        environment = next((item for item in environments if item.get("name") == name), None)
        if environment is None:
            names = ", ".join(str(item.get("name")) for item in environments)
            raise MigrationError(f"environment {name!r} not found; available: {names}")
    else:
        environment = next((item for item in environments if item.get("default")), None)
        if environment is None:
            environment = next((item for item in environments if item.get("name") == "local"), None)
        if environment is None:
            raise MigrationError("no default/local environment in environment.json")

    selected_name = str(environment.get("name") or "")
    base = str(environment.get("admin_url", "")).rstrip("/")
    parsed = urllib.parse.urlparse(base)
    if parsed.scheme not in ("http", "https") or not parsed.hostname:
        raise MigrationError(f"environment {selected_name!r} has an invalid admin_url")
    if selected_name == "local" and parsed.hostname not in ("127.0.0.1", "localhost"):
        raise MigrationError(f"environment 'local' must point at 127.0.0.1, got {base}")
    token = str(environment.get("admin_access_token") or "")
    if not token or token.startswith("<"):
        raise MigrationError(f"environment {selected_name!r} has no access token")
    return selected_name, base, token


class EzyClient:
    def __init__(self, env_name: str | None = None) -> None:
        self.env_name, self.base, token = load_environment(env_name)
        self.headers = {
            "Authorization": "Bearer " + token,
            "User-Agent": "tqd-migrate/1.0",
            "Accept": "application/json",
        }

    def request(self, method: str, path: str, body: Any | None = None) -> Any:
        data = None
        headers = dict(self.headers)
        if body is not None:
            data = json.dumps(body, ensure_ascii=False).encode("utf-8")
            headers["Content-Type"] = "application/json"
        request = urllib.request.Request(self.base + path, data=data, headers=headers, method=method)
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                raw = response.read()
                if not raw:
                    return None
                try:
                    return json.loads(raw)
                except json.JSONDecodeError:
                    return raw.decode("utf-8", "replace")
        except urllib.error.HTTPError as err:
            detail = err.read().decode("utf-8", "replace")[:600]
            raise MigrationError(f"{method} {path} -> HTTP {err.code}: {detail}") from err
        except urllib.error.URLError as err:
            raise MigrationError(f"{method} {path} failed: {err.reason}") from err

    def media_contains(self, name: str) -> bool:
        quoted = urllib.parse.quote(name)
        data = self.request("GET", f"/api/v1/media/{quoted}/contains")
        return bool(data and data.get("contains"))

    def upload_media(self, name: str, data: bytes, mime_type: str) -> None:
        boundary = "----tqdmigrate" + os.urandom(16).hex()
        head = (
            f"--{boundary}\r\n"
            f'Content-Disposition: form-data; name="file"; filename="{name}"\r\n'
            f"Content-Type: {mime_type}\r\n\r\n"
        ).encode()
        body = head + data + f"\r\n--{boundary}--\r\n".encode()
        headers = {
            "Authorization": self.headers["Authorization"],
            "User-Agent": self.headers["User-Agent"],
            "Content-Type": f"multipart/form-data; boundary={boundary}",
            "Accept": "application/json",
        }
        request = urllib.request.Request(
            self.base + "/api/v1/media/add?notPublic=false", data=body, headers=headers, method="POST"
        )
        try:
            with urllib.request.urlopen(request, timeout=120) as response:
                raw = response.read()
                if response.status != 200:
                    raise MigrationError(f"upload {name} returned HTTP {response.status}: {raw[:300]!r}")
        except urllib.error.HTTPError as err:
            detail = err.read().decode("utf-8", "replace")[:300]
            raise MigrationError(f"upload {name} -> HTTP {err.code}: {detail}") from err
        except urllib.error.URLError as err:
            raise MigrationError(f"upload {name} failed: {err.reason}") from err
        if not self.media_contains(name):
            raise MigrationError(f"{name} uploaded but /contains still reports false")

    def list_posts(self) -> list[dict[str, Any]]:
        items: list[dict[str, Any]] = []
        token: str | None = None
        while True:
            query = "?limit=100"
            if token:
                query += "&nextPageToken=" + urllib.parse.quote(token)
            page = self.request("GET", "/ezyarticle/api/v1/posts" + query) or {}
            items.extend(page.get("items") or [])
            token = (page.get("pageToken") or {}).get("next")
            if not token or not (page.get("continuation") or {}).get("hasNext"):
                break
        return items

    def post_meta_list(self, post_id: int) -> list[dict[str, Any]]:
        data = self.request("GET", f"/ezyarticle/api/v1/posts/{post_id}/meta-list?limit=100") or {}
        if not isinstance(data, dict):
            raise MigrationError(f"post {post_id} meta-list returned an unexpected payload")
        items = data.get("items") or []
        if not isinstance(items, list):
            raise MigrationError(f"post {post_id} meta-list items are not a list")
        return items

    def add_post_meta(self, post_id: int, meta_key: str, meta_value: str) -> int:
        data = self.request(
            "POST",
            f"/ezyarticle/api/v1/posts/{post_id}/meta/add",
            {"metaKey": meta_key, "metaValue": meta_value},
        )
        if not isinstance(data, dict) or not data.get("addedId"):
            raise MigrationError(f"post {post_id} meta/add returned no addedId: {data!r}")
        return int(data["addedId"])

    def update_post_meta(self, meta_id: int, meta_key: str, meta_value: str) -> None:
        self.request(
            "PUT",
            f"/ezyarticle/api/v1/post-meta/{meta_id}",
            {"metaKey": meta_key, "metaValue": meta_value},
        )

    def delete_post_meta(self, meta_id: int) -> None:
        self.request("DELETE", f"/ezyarticle/api/v1/post-meta/{meta_id}")


def epoch_ms(published_at: str | None) -> int:
    if not published_at:
        return 0
    try:
        moment = dt.datetime.strptime(published_at, "%Y-%m-%d %H:%M:%S")
    except ValueError as err:
        raise MigrationError(f"bad publishedAt {published_at!r}") from err
    # D1 stores Indochina wall-clock strings (the old admin entered them that way and rendered them verbatim).
    # Attaching that zone explicitly gives the same epoch on a VN laptop and on a UTC VPS.
    return int(moment.replace(tzinfo=VN_TZ).timestamp() * 1000)


def create_payload(meta: dict[str, Any], content: str) -> dict[str, Any]:
    return {
        "title": meta["title"],
        "summary": meta.get("summary", ""),
        "additionalHead": "",
        "additionalFoot": "",
        "pageFragmentPageName": "",
        "pageFragmentName": "",
        "content": content,
        "contentType": meta.get("contentType", "HTML"),
        "featuredImageId": 0,
        "faviconImageId": 0,
        "videoId": 0,
        "audioId": 0,
        "parentId": 0,
        "publishedAt": epoch_ms(meta.get("publishedAt")),
        "status": meta["status"],
        "commentStatus": "CLOSE",
        "menuId": 0,
        "language": "vi",
        "termIds": [],
        "priority": int(meta.get("priority", 0)),
        "slug": meta["slug"],
        "postType": meta["postType"],
        "actualAuthorAdminId": 0,
        "actualAuthorUserId": 0,
        "metadata": {},
    }


def update_payload(live: dict[str, Any], meta: dict[str, Any], content: str) -> dict[str, Any]:
    payload = {field: live.get(field) or "" for field in API_POST_FIELDS}
    payload.update(
        {
            "title": meta["title"],
            "summary": meta.get("summary", ""),
            "content": content,
            "contentType": meta.get("contentType", "HTML"),
            "status": meta["status"],
            "postType": meta["postType"],
            "slug": meta["slug"],
        }
    )
    payload["language"] = "vi"
    return payload


def load_local_posts() -> list[dict[str, Any]]:
    if not POSTS_DIR.is_dir():
        raise MigrationError(f"posts directory not found: {POSTS_DIR} (run generate first)")
    posts: list[dict[str, Any]] = []
    for meta_path in sorted(POSTS_DIR.glob("*/meta.json")):
        folder = meta_path.parent
        content_path = folder / "content.html"
        if not content_path.is_file():
            raise MigrationError(f"{folder.name}: content.html is missing")
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as err:
            raise MigrationError(f"{meta_path} is invalid JSON: {err}") from err
        for field in ("slug", "title", "postType", "status"):
            if not meta.get(field):
                raise MigrationError(f"{meta_path}: missing {field}")
        if meta["slug"] != folder.name:
            raise MigrationError(f"{meta_path}: slug {meta['slug']!r} does not match folder name")
        if meta["postType"] not in POST_TYPES:
            raise MigrationError(f"{meta_path}: unexpected postType {meta['postType']!r}")
        if meta["status"] not in ("PUBLISHED", "DRAFT"):
            raise MigrationError(f"{meta_path}: unexpected status {meta['status']!r}")
        meta["_content"] = content_path.read_text(encoding="utf-8")
        posts.append(meta)
    return posts


