#!/usr/bin/env python3
"""Migrate tqd.me D1 content and R2 media into an EzyPlatform environment.

Commands (run from the repository root):

    python tools/migrate/migrate.py generate
        Read .artifacts/d1/tqd_db.sql and write posts/<slug>/{content.html,meta.json}
        for articles, product/video items and gallery entries. Also writes
        tools/migrate/media-map.json. No network access.

    python tools/migrate/migrate.py media
        Download every row of the D1 `media` table from https://tqd.me/media/<key>
        into api/v1/media/<key with / replaced by ->. Existing files with the
        expected size are skipped. No external libraries.

    python tools/migrate/migrate.py upload-media [--apply] [--env NAME]
        Upload those files to the selected EzyPlatform media library with the
        MIME type recorded in D1. Dry run unless --apply is given. This exists
        because the bundled ezy-media skill sends multipart parts as
        application/octet-stream, which the platform rejects for WebP and MP4
        (400 {"fileType":"invalid"}).

    python tools/migrate/migrate.py publish [--apply] [--env NAME]
        Create or update the generated posts on the selected EzyPlatform
        environment, then sync article tags (`tqd_tags` post meta). Dry run
        unless --apply is given. The bundled ezy-publish skill can only update
        existing pages/fragments, so post creation uses the same endpoints as
        the admin editor.

    python tools/migrate/migrate.py tags [--apply] [--env NAME]
        Repair/sync only the `tqd_tags` post meta for migrated articles.

    python tools/migrate/migrate.py verify [--env NAME]
        Read-only check: count migrated posts by type/status, compare every local
        post against the server, check `tqd_tags`, and confirm all mapped media
        is in the library.

`--env` selects an entry by `name` in environment.json (default: the entry with
`"default": true`, else `local`). Tokens are never printed. Example:
`python tools/migrate/migrate.py publish --apply --env production`.

`generate` is idempotent: identical files are left untouched and post folders that
were generated by a previous run but are no longer produced are removed.
"""
