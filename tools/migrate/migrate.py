def verify(env_name: str | None = None) -> dict[str, Any]:
    client = EzyClient(env_name)
    posts = client.list_posts()
    by_type: dict[str, int] = {}
    by_status: dict[str, int] = {}
    for post in posts:
        by_type[post.get("postType", "?")] = by_type.get(post.get("postType", "?"), 0) + 1
        by_status[post.get("status", "?")] = by_status.get(post.get("status", "?"), 0) + 1

    local = load_local_posts()
    live_by_slug = {post.get("slug"): post for post in posts}
    missing: list[str] = []
    mismatches: list[dict[str, Any]] = []
    tags_checked = 0
    tags_missing: list[str] = []
    tags_mismatched: list[dict[str, Any]] = []
    missing_covers: list[str] = []
    wrong_covers: list[dict[str, Any]] = []
    for meta in local:
        slug = meta["slug"]
        live = live_by_slug.get(slug)
        if not live:
            missing.append(slug)
            if meta.get("postType") == "POST" and meta.get("tags"):
                tags_missing.append(slug)
            continue
        full = client.request("GET", f"/ezyarticle/api/v1/posts/{live['id']}") or {}
        bad = [
            field
            for field in ("content", "status", "postType", "title", "summary")
            if (full.get(field) or "") != (meta["_content"] if field == "content" else meta.get(field, ""))
        ]
        if bad:
            mismatches.append({"slug": slug, "fields": bad})

        if meta.get("postType") == "POST":
            tags_checked += 1
            expected_tags = compact_tags(meta.get("tags") or [])
            meta_rows = client.post_meta_list(int(live["id"]))
            matches = [item for item in meta_rows if item.get("metaKey") == TAGS_META_KEY]
            if len(matches) != 1:
                tags_missing.append(slug)
            elif str(matches[0].get("metaValue") or "") != expected_tags:
                tags_mismatched.append({"slug": slug, "expected": expected_tags, "actual": matches[0].get("metaValue")})
            covers = [item for item in meta_rows if item.get("metaKey") == COVER_META_KEY]
            expected_cover = meta.get("cover") or ""
            if len(covers) != 1:
                missing_covers.append(slug)
            elif str(covers[0].get("metaValue") or "") != expected_cover:
                wrong_covers.append({"slug": slug, "expected": expected_cover, "actual": covers[0].get("metaValue")})

    mapping = json.loads(MEDIA_MAP_PATH.read_text(encoding="utf-8")) if MEDIA_MAP_PATH.is_file() else {}
    missing_media = [name for name in mapping.values() if not client.media_contains(name)]
    ours = [post for post in posts if post.get("postType") in POST_TYPES]
    return {
        "serverPosts": len(posts),
        "migratedPosts": len(ours),
        "byPostType": by_type,
        "byStatus": by_status,
        "localPosts": len(local),
        "missingOnServer": missing,
        "contentMismatches": mismatches,
        "articlesWithTags": sum(1 for meta in local if meta.get("postType") == "POST" and meta.get("tags")),
        "tagsChecked": tags_checked,
        "tagsMissing": tags_missing,
        "tagsMismatched": tags_mismatched,
        "mediaMapped": len(mapping),
        "mediaMissingOnServer": missing_media,
        "coversMissing": missing_covers,
        "coversMismatched": wrong_covers,
    }


