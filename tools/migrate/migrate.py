def publish(apply: bool, env_name: str | None = None) -> dict[str, Any]:
    posts = load_local_posts()
    client = EzyClient(env_name)
    live_by_slug = {}
    for live in client.list_posts():
        slug = live.get("slug")
        if slug in live_by_slug:
            raise MigrationError(f"server has duplicate post slug {slug!r}")
        live_by_slug[slug] = live

    # The web list function orders by publishedAt DESC, id DESC, so the first card of a list must be created last:
    # creation order = reverse of the intended order (priority counts up with the intended order).
    posts.sort(key=lambda item: (-int(item.get("priority") or 0), item["slug"]))

    actions: list[dict[str, Any]] = []
    created = updated = unchanged = 0
    failures: list[str] = []

    for meta in posts:
        slug = meta["slug"]
        live = live_by_slug.get(slug)
        if live is None:
            actions.append({"action": "create", "slug": slug, "postType": meta["postType"], "status": meta["status"]})
            if not apply:
                continue
            try:
                result = client.request("POST", "/ezyarticle/api/v1/posts/add", create_payload(meta, meta["_content"]))
                if not isinstance(result, dict) or not result.get("id"):
                    raise MigrationError(f"create returned no post id: {result!r}")
                after = client.request("GET", f"/ezyarticle/api/v1/posts/{result['id']}")
                if not after:
                    raise MigrationError("created post cannot be read back")
                if after.get("content") != meta["_content"]:
                    raise MigrationError("content differs right after creation")
                for field in ("title", "status", "postType", "slug", "summary"):
                    if (after.get(field) or "") != meta.get(field, ""):
                        raise MigrationError(f"{field} differs right after creation")
                if meta.get("publishedAt") and int(after.get("publishedAt") or 0) != epoch_ms(meta["publishedAt"]):
                    raise MigrationError(
                        f"publishedAt is {after.get('publishedAt')}, expected {epoch_ms(meta['publishedAt'])}"
                    )
                live_by_slug[slug] = after
                created += 1
                print(f"  + created {slug} (id {result['id']}, {meta['postType']}, {meta['status']})")
            except MigrationError as err:
                failures.append(f"create {slug}: {err}")
                print(f"  x create {slug}: {err}", file=sys.stderr)
                break
            continue

        if live.get("postType") not in POST_TYPES:
            raise MigrationError(
                f"slug {slug!r} already exists as {live.get('postType')} (id {live.get('id')}); refusing to overwrite"
            )
        current = client.request("GET", f"/ezyarticle/api/v1/posts/{live['id']}")
        if not current:
            raise MigrationError(f"cannot read live post {live['id']} for {slug}")
        changes = {
            "title": meta["title"],
            "content": meta["_content"],
            "summary": meta.get("summary", ""),
            "contentType": meta.get("contentType", "HTML"),
            "status": meta["status"],
            "postType": meta["postType"],
            "slug": meta["slug"],
        }
        diff = {field: value for field, value in changes.items() if (current.get(field) or "") != value}
        priority = int(meta.get("priority", 0))
        priority_differs = int(current.get("priority") or 0) != priority
        published_differs = bool(meta.get("publishedAt")) and int(current.get("publishedAt") or 0) != epoch_ms(meta["publishedAt"])

        if not diff and not priority_differs:
            unchanged += 1
            actions.append({"action": "unchanged", "slug": slug, "postId": current["id"]})
            if published_differs:
                print(
                    f"  ! {slug}: publishedAt on server is {current.get('publishedAt')}, "
                    f"local {epoch_ms(meta['publishedAt'])} (the API does not update it)",
                    file=sys.stderr,
                )
            continue

        actions.append(
            {
                "action": "update",
                "slug": slug,
                "postId": current["id"],
                "fields": sorted(diff) + (["priority"] if priority_differs else []),
            }
        )
        if not apply:
            continue
        try:
            if diff:
                client.request("PUT", f"/ezyarticle/api/v1/posts/{current['id']}", update_payload(current, meta, meta["_content"]))
            if priority_differs:
                client.request("PUT", f"/ezyarticle/api/v1/posts/{current['id']}/priority", {"priority": priority})
            after = client.request("GET", f"/ezyarticle/api/v1/posts/{current['id']}")
            if not after:
                raise MigrationError("updated post cannot be read back")
            for field, value in diff.items():
                if (after.get(field) or "") != value:
                    raise MigrationError(f"{field} differs after update")
            if int(after.get("priority") or 0) != priority:
                raise MigrationError(f"priority is {after.get('priority')}, expected {priority}")
            updated += 1
            print(f"  ~ updated {slug} (id {current['id']}: {', '.join(sorted(diff) + (['priority'] if priority_differs else []))})")
        except MigrationError as err:
            failures.append(f"update {slug}: {err}")
            print(f"  x update {slug}: {err}", file=sys.stderr)
            break

    tag_report: dict[str, Any] | None = None
    if not failures:
        tag_report = tags_report(
            client,
            posts,
            live_by_slug,
            apply,
            "tags-report.json" if apply else "tags-plan.json",
        )
        failures.extend(tag_report["failures"])

    report = {
        "applied": apply,
        "posts": len(posts),
        "create": sum(1 for action in actions if action["action"] == "create"),
        "update": sum(1 for action in actions if action["action"] == "update"),
        "unchanged": sum(1 for action in actions if action["action"] == "unchanged"),
        "created": created,
        "updated": updated,
        "tags": tag_report,
        "failures": failures,
    }
    write_json(MIGRATE_DIR / ("publish-report.json" if apply else "publish-plan.json"), {"report": report, "actions": actions})
    if failures:
        raise MigrationError(f"publish stopped: {failures[-1]}")
    return report


