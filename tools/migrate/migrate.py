def sync_post_meta(client: EzyClient, post_id: int, key: str, value: str, apply: bool) -> dict[str, Any]:
    """Ensure the post has exactly one <key> meta with this value (an empty value clears stale metadata)."""
    matches = [meta for meta in client.post_meta_list(post_id) if meta.get("metaKey") == key]
    if len(matches) > 1:
        ids = ", ".join(str(meta.get("id")) for meta in matches)
        raise MigrationError(f"post {post_id} has duplicate {key} meta ids: {ids}")

    if value == "":
        # The API rejects an empty metaValue ("required"), so clearing a stale meta means deleting it.
        if not matches:
            return {"action": "unchanged", "postId": post_id, "metaId": None}
        meta_id = int(matches[0]["id"])
        if apply:
            client.delete_post_meta(meta_id)
            left = [meta for meta in client.post_meta_list(post_id) if meta.get("metaKey") == key]
            if left:
                raise MigrationError(f"post {post_id} {key} was not deleted")
        return {"action": "delete", "postId": post_id, "metaId": meta_id}

    if not matches:
        if apply:
            client.add_post_meta(post_id, key, value)
        action = "add"
        meta_id = None
    else:
        meta_id = int(matches[0]["id"])
        current = str(matches[0].get("metaValue") or "")
        if current == value:
            return {"action": "unchanged", "postId": post_id, "metaId": meta_id}
        if apply:
            client.update_post_meta(meta_id, key, value)
        action = "update"

    if apply:
        after = [meta for meta in client.post_meta_list(post_id) if meta.get("metaKey") == key]
        if len(after) != 1 or str(after[0].get("metaValue") or "") != value:
            raise MigrationError(f"post {post_id} {key} did not persist correctly")
        meta_id = int(after[0]["id"])
    return {"action": action, "postId": post_id, "metaId": meta_id}


def tags_report(
    client: EzyClient,
    posts: list[dict[str, Any]],
    live_by_slug: dict[str, dict[str, Any]],
    apply: bool,
    filename: str,
) -> dict[str, Any]:
    actions: list[dict[str, Any]] = []
    failures: list[str] = []
    # every article is checked, including the untagged ones: dropping all tags must clear the stored JSON too
    articles = [meta for meta in posts if meta.get("postType") == "POST"]

    for meta in articles:
        slug = meta["slug"]
        live = live_by_slug.get(slug)
        if not live:
            actions.append({"slug": slug, "action": "pending-create"})
            continue
        try:
            action = sync_post_tags(client, int(live["id"]), meta.get("tags") or [], apply)
            actions.append({"slug": slug, **action})
        except MigrationError as err:
            failures.append(f"tags {slug}: {err}")
            print(f"  x tags {slug}: {err}", file=sys.stderr)
            continue
        try:
            cover = sync_post_meta(client, int(live["id"]), COVER_META_KEY, meta.get("cover") or "", apply)
            actions.append({"slug": slug, "action": "cover-" + cover["action"], "metaId": cover["metaId"]})
        except MigrationError as err:
            failures.append(f"cover {slug}: {err}")
            print(f"  x cover {slug}: {err}", file=sys.stderr)

    report = {
        "applied": apply,
        "articlesWithTags": sum(1 for meta in articles if meta.get("tags")),
        "checked": len(actions),
        "add": sum(1 for action in actions if action["action"] == "add"),
        "update": sum(1 for action in actions if action["action"] == "update"),
        "unchanged": sum(1 for action in actions if action["action"] == "unchanged"),
        "pendingCreate": sum(1 for action in actions if action["action"] == "pending-create"),
        "failures": failures,
    }
    write_json(MIGRATE_DIR / filename, {"report": report, "actions": actions})
    return report


def sync_tags(apply: bool, env_name: str | None = None) -> dict[str, Any]:
    client = EzyClient(env_name)
    posts = load_local_posts()
    live_by_slug: dict[str, dict[str, Any]] = {}
    for live in client.list_posts():
        slug = live.get("slug")
        if slug:
            live_by_slug[slug] = live
    report = tags_report(
        client,
        posts,
        live_by_slug,
        apply,
        "tags-report.json" if apply else "tags-plan.json",
    )
    if report["failures"]:
        raise MigrationError(f"tags sync stopped: {report['failures'][-1]}")
    return report


