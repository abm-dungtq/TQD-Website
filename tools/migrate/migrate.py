def read_gallery(conn: sqlite3.Connection) -> list[dict[str, Any]]:
    row = conn.execute("SELECT value FROM settings WHERE key = 'gallery'").fetchone()
    if not row:
        raise MigrationError("settings.gallery is missing from the dump")
    try:
        gallery = json.loads(row["value"])
    except json.JSONDecodeError as err:
        raise MigrationError(f"settings.gallery is not valid JSON: {err}") from err
    if not isinstance(gallery, list):
        raise MigrationError("settings.gallery must be a JSON array")
    for entry in gallery:
        if not isinstance(entry, dict) or not entry.get("key") or not entry.get("caption"):
            raise MigrationError(f"gallery entry needs key and caption: {entry!r}")
    return gallery


def generate(conn: sqlite3.Connection) -> dict[str, Any]:
    name_by_key = parse_media_keys(conn)
    media_rows = {row["key"]: dict(row) for row in conn.execute("SELECT * FROM media")}

    articles = [dict(row) for row in conn.execute("SELECT * FROM articles ORDER BY id")]
    if len(articles) != EXPECTED_ARTICLES:
        raise MigrationError(f"expected {EXPECTED_ARTICLES} articles, found {len(articles)}")
    items = [dict(row) for row in conn.execute("SELECT * FROM items ORDER BY kind, sort, id")]
    if len(items) != EXPECTED_ITEMS:
        raise MigrationError(f"expected {EXPECTED_ITEMS} items, found {len(items)}")
    gallery = read_gallery(conn)

    product_cards = load_snapshot_cards("page_san-pham", ARTICLE_RE, H2_RE)
    video_cards = load_snapshot_cards("page_video-ai", ARTICLE_RE, H2_RE)
    gallery_cards = load_snapshot_cards("page_thu-vien", FIGURE_RE, FIGCAPTION_RE)

    generated: list[dict[str, Any]] = []
    fallbacks: list[str] = []
    removed_scripts = 0
    tagged_articles = 0
    used: dict[str, set[str]] = {"product": set(), "video": set(), "gallery": set()}

    def add_post(slug: str, title: str, summary: str, post_type: str, status: str,
                 content: str, published_at: str | None, priority: int,
                 source: str, tags: list[str] | None = None, cover: str | None = None) -> None:
        meta: dict[str, Any] = {
            "slug": slug,
            "title": title,
            "summary": summary,
            "postType": post_type,
            "contentType": "HTML",
            "status": status,
        }
        if tags:
            meta["tags"] = tags
        if cover:
            meta["cover"] = cover
        if published_at:
            if not DATETIME_RE.match(published_at):
                raise MigrationError(f"{slug}: publishedAt must be yyyy-MM-dd HH:mm:ss, got {published_at!r}")
            meta["publishedAt"] = published_at
        if priority:
            meta["priority"] = priority
        folder = POSTS_DIR / slug
        changed_content = write_if_changed(folder / "content.html", content)
        changed_meta = write_json(folder / "meta.json", meta)
        generated.append(
            {
                "slug": slug,
                "postType": post_type,
                "status": status,
                "source": source,
                "changed": changed_content or changed_meta,
            }
        )

    # 1. Articles -> POST
    # priority counts up with the published order; the platform's list function sorts by publishedAt/id, but the
    # API assigns ids in creation order, so publish() creates in reverse-priority order to pin the tie-break.
    for article_index, article in enumerate(articles, start=1):
        slug = article["slug"]
        content = rewrite_media_urls(article["body_html"], name_by_key, f"article:{slug}")
        status = "PUBLISHED" if article["status"] == "published" else "DRAFT"
        tags = parse_article_tags(article["tags"])
        if tags:
            tagged_articles += 1
        add_post(
            slug=slug,
            title=article["title"],
            summary=article["summary"],
            post_type="POST",
            status=status,
            content=content,
            published_at=article["published_at"],
            priority=len(articles) + 1 - article_index,
            source=f"article:{article['id']}",
            tags=tags,
            cover=name_by_key.get(article["cover_key"] or ""),
        )

    # 2. Items -> tqd_product / tqd_video, ordered by sort/id and prioritised
    for kind, post_type, prefix, pool, pool_name in (
        ("product", "tqd_product", "sp", product_cards, "san-pham"),
        ("video", "tqd_video", "video", video_cards, "video-ai"),
    ):
        rows = [item for item in items if item["kind"] == kind]
        for index, item in enumerate(rows):
            title = item["title"]
            slug = f"{prefix}-{item['id']}-{slugify(title)}"
            card = pool.get(title)
            if card is None:
                card = build_item_card(item, name_by_key)
                fallbacks.append(f"{slug} (not in {pool_name} snapshot)")
            else:
                used[kind].add(title)
            card, stripped = strip_runtime_markup(card)
            removed_scripts += stripped
            content = rewrite_media_urls(card, name_by_key, f"item:{item['id']}")
            add_post(
                slug=slug,
                title=title,
                summary=item["summary"],
                post_type=post_type,
                status="PUBLISHED" if item["visible"] else "DRAFT",
                content=content,
                published_at=published_at_from_item_date(item["date"]),
                priority=index + 1,
                source=f"{kind}:{item['id']}",
            )

    # 3. Gallery -> tqd_gallery
    for index, entry in enumerate(gallery, start=1):
        caption = str(entry["caption"])
        key = str(entry["key"])
        slug = f"tv-{index}-{slugify(caption, max_len=120)}"
        card = gallery_cards.get(caption)
        if card is None:
            card = build_gallery_card(entry, name_by_key)
            fallbacks.append(f"{slug} (not in thu-vien snapshot)")
        else:
            used["gallery"].add(caption)
        card, stripped = strip_runtime_markup(card)
        removed_scripts += stripped
        content = rewrite_media_urls(card, name_by_key, f"gallery:{index}")
        published_at = media_rows.get(key, {}).get("created_at")
        add_post(
            slug=slug,
            title=caption,
            summary=caption,
            post_type="tqd_gallery",
            status="PUBLISHED",
            content=content,
            published_at=published_at,
            priority=index,
            source=f"gallery:{index}",
        )

    # Prune folders produced by a previous run but absent from this one.
    pruned: list[str] = []
    wanted = {entry["slug"] for entry in generated}
    if MANIFEST_PATH.is_file():
        try:
            previous = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        except json.JSONDecodeError as err:
            raise MigrationError(f"previous manifest is corrupt: {err}") from err
        for old in previous.get("dirs", []):
            if old in wanted:
                continue
            folder = POSTS_DIR / old
            meta_path = folder / "meta.json"
            if meta_path.is_file():
                meta = json.loads(meta_path.read_text(encoding="utf-8"))
                if meta.get("slug") == old:
                    shutil.rmtree(folder)
                    pruned.append(old)

    write_json(MEDIA_MAP_PATH, name_by_key)

    snapshot_leftovers = {
        pool_name: sorted(set(pool) - used[kind])
        for kind, pool, pool_name in (
            ("product", product_cards, "san-pham"),
            ("video", video_cards, "video-ai"),
            ("gallery", gallery_cards, "thu-vien"),
        )
        if set(pool) - used[kind]
    }

    report = {
        "generatedAt": dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "counts": {
            "articles": len(articles),
            "items": len(items),
            "itemsByKind": {kind: sum(1 for i in items if i["kind"] == kind) for kind in ("product", "video")},
            "gallery": len(gallery),
            "media": len(name_by_key),
            "posts": len(generated),
            "draft": sum(1 for entry in generated if entry["status"] == "DRAFT"),
            "articlesWithTags": tagged_articles,
        },
        "byPostType": {
            post_type: sum(1 for entry in generated if entry["postType"] == post_type)
            for post_type in sorted({entry["postType"] for entry in generated})
        },
        "fallbacks": fallbacks,
        "snapshotUnused": snapshot_leftovers,
        "removedAstroScriptsOrAttrs": removed_scripts,
        "prunedFolders": pruned,
    }
    write_json(REPORT_PATH, report)
    write_json(
        MANIFEST_PATH,
        {
            "generatedAt": report["generatedAt"],
            "dirs": sorted(wanted),
            "posts": generated,
        },
    )
    return report


